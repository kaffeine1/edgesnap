"""Lay out the autodoc of edgesnap.library, docs/autodocs/edgesnap.doc.

The documentation lives once, in include/edgesnap.h, as autodoc blocks:

    /****** edgesnap.library/ESnap_SnapWindow *********************
     *
     * NAME
     *     ESnap_SnapWindow -- put a window in a zone (V2)
     *
     * FUNCTION
     *     ...
     */

This script only gives them the shape of an Amiga SDK's autodocs. The
SYNOPSIS of every function is built here, from the registers in
library/morphos/edgesnap_lib.fd and the prototype in the header, so a
block never carries one of its own and the two can never disagree.

    make-autodoc.py           write docs/autodocs/edgesnap.doc
    make-autodoc.py --check   fail when a function of the .fd has no
                              block, a block names no function, a block
                              is malformed, the AROS .fd disagrees with
                              the MorphOS one, or the .doc is not up to
                              date
"""

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HEADER = os.path.join(ROOT, "include", "edgesnap.h")
FD = os.path.join(ROOT, "library", "morphos", "edgesnap_lib.fd")
# Generated by genmodule from library/aros/edgesnap.conf: the same
# vectors with the same registers, or a client built on one system
# calls another function on the other.
AROS_FD = os.path.join(ROOT, "include", "aros", "edgesnap_lib.fd")
OUT = os.path.join(ROOT, "docs", "autodocs", "edgesnap.doc")

LIB = "edgesnap.library"
WIDTH = 77

# What the result is called in the SYNOPSIS when it is not an error code.
RESULT_NAMES = {
    "ESnap_QueryCapabilities": "caps",
    "ESnap_QueryGeneration": "generation",
}

SECTIONS = ("NAME", "SYNOPSIS", "PURPOSE", "FUNCTION", "INPUTS", "TAGS",
            "FLAGS", "RESULT", "EXAMPLE", "NOTES", "BUGS", "SEE ALSO")

BLOCK_START = re.compile(r"^/\*{6} " + re.escape(LIB) + r"/(\S+) \*+$")


class Failure(Exception):
    pass


def read(path):
    with open(path, encoding="ascii") as f:
        return f.read()


def parse_fd(text):
    """The functions in vector order: name, argument names, registers."""
    funcs = []
    public = False
    for line in text.splitlines():
        line = line.strip()
        if line.startswith("##public"):
            public = True
            continue
        if line.startswith("##end"):
            break
        if not public or not line or line.startswith("*") or \
                line.startswith("##"):
            continue
        m = re.match(r"^(\w+)\(([^)]*)\)\(([^)]*)\)$", line)
        if not m:
            raise Failure("fd: cannot read %r" % line)
        args = [a for a in m.group(2).split(",") if a]
        regs = [r.strip().upper() for r in m.group(3).split(",") if r.strip()]
        if len(args) != len(regs):
            raise Failure("fd: %s has %d arguments and %d registers"
                          % (m.group(1), len(args), len(regs)))
        funcs.append((m.group(1), args, regs))
    return funcs


def parse_prototypes(text):
    """name -> (return type, [(type, name)]) for every ESnap_ prototype."""
    protos = {}
    pattern = re.compile(r"^(LONG|ULONG|void)\s+(ESnap_\w+)\s*\(([^;]*)\)\s*;",
                         re.M)
    for m in pattern.finditer(text):
        params = " ".join(m.group(3).split())
        args = []
        if params != "void":
            for p in params.split(","):
                p = p.strip()
                am = re.match(r"^(.*?)(\w+)$", p)
                if not am:
                    raise Failure("header: cannot read parameter %r of %s"
                                  % (p, m.group(2)))
                args.append((am.group(1).strip(), am.group(2)))
        protos[m.group(2)] = (m.group(1), args)
    return protos


def parse_blocks(text):
    """[(name, [section, [lines]])] in the order of the header."""
    blocks = []
    lines = text.splitlines()
    i = 0
    while i < len(lines):
        m = BLOCK_START.match(lines[i])
        if not m:
            i += 1
            continue
        name = m.group(1)
        body = []
        i += 1
        while i < len(lines) and lines[i].strip() != "*/":
            raw = lines[i]
            if raw == " *":
                body.append("")
            elif raw.startswith(" * "):
                body.append(raw[3:].rstrip())
            else:
                raise Failure("%s: line %d of the block does not start "
                              "with ' * ': %r" % (name, i + 1, raw))
            i += 1
        if i == len(lines):
            raise Failure("%s: the block never ends" % name)
        blocks.append((name, split_sections(name, body)))
        i += 1
    return blocks


def split_sections(name, body):
    sections = []
    for line in body:
        if line and not line.startswith(" "):
            if line not in SECTIONS:
                raise Failure("%s: %r is not a section" % (name, line))
            if line == "SYNOPSIS":
                raise Failure("%s: SYNOPSIS is built from the .fd, the "
                              "block must not carry one" % name)
            if any(s == line for s, _ in sections):
                raise Failure("%s: two %s sections" % (name, line))
            sections.append((line, []))
        elif not sections:
            if line:
                raise Failure("%s: text before the first section" % name)
        else:
            if line and not line.startswith("    "):
                raise Failure("%s: %s text must be indented four spaces: %r"
                              % (name, sections[-1][0], line))
            sections[-1][1].append(line[4:])
    for _, text in sections:
        while text and not text[-1]:
            text.pop()
        while text and not text[0]:
            text.pop(0)
    return sections


def synopsis(name, fd_args, regs, proto):
    ret, args = proto
    if len(args) != len(regs):
        raise Failure("%s: the prototype has %d arguments, the .fd %d"
                      % (name, len(args), len(regs)))
    head = ""
    if ret != "void":
        head = RESULT_NAMES.get(name, "error") + " = "
    call = head + name + "("
    reg_line = "D0" if ret != "void" else ""
    for n, (_, aname) in enumerate(args):
        if n:
            call += ", "
        col = len(call)
        call += aname
        reg_line = reg_line.ljust(col) + regs[n]
    call += ")"
    out = [call]
    if reg_line:
        out.append(reg_line)
    out.append("")
    first = "%s %s(" % (ret, name)
    params = ["%s%s%s" % (t, "" if t.endswith("*") else " ", a)
              for t, a in args] or ["void"]
    line = first
    for n, p in enumerate(params):
        piece = p + (");" if n == len(params) - 1 else ",")
        if line != first and len(line) + 1 + len(piece) > 70:
            out.append(line.rstrip())
            line = " " * len(first) + piece
        else:
            line += ("" if line == first else " ") + piece
    out.append(line)
    return out


def heading(name):
    """The name at both ends of the line, as the SDKs have it; once when
    twice would run past the width."""
    left = "%s/%s" % (LIB, name)
    if 2 * len(left) + 2 > WIDTH:
        return left
    return left + " " * (WIDTH - 2 * len(left)) + left


def build(header_text, fd_text, aros_fd_text=None):
    funcs = parse_fd(fd_text)
    if aros_fd_text is not None:
        aros = parse_fd(aros_fd_text)
        if [(f[0], f[2]) for f in funcs] != [(f[0], f[2]) for f in aros]:
            raise Failure("include/aros/edgesnap_lib.fd and "
                          "library/morphos/edgesnap_lib.fd disagree on "
                          "the functions or their registers")
    protos = parse_prototypes(header_text)
    blocks = parse_blocks(header_text)

    fd_names = [f[0] for f in funcs]
    seen = {}
    for name, sections in blocks:
        if name in seen:
            raise Failure("%s: two blocks" % name)
        seen[name] = sections
        topic = name.startswith("--") and name.endswith("--")
        if not topic and name not in fd_names:
            raise Failure("%s: a block for a function the .fd does not "
                          "have" % name)
        names = [s for s, _ in sections]
        if not topic:
            if not names or names[0] != "NAME":
                raise Failure("%s: NAME must come first" % name)
            if "FUNCTION" not in names or "RESULT" not in names:
                raise Failure("%s: FUNCTION and RESULT are required" % name)
            title = sections[0][1]
            if len(title) != 1 or not title[0].startswith(name + " -- ") or \
                    not re.search(r"\(V2(\.\d+)?\)$", title[0]):
                raise Failure("%s: NAME must read '%s -- what it does "
                              "(V2.n)'" % (name, name))
            if name not in protos:
                raise Failure("%s: no prototype in the header" % name)
        elif "PURPOSE" not in names:
            raise Failure("%s: a topic needs a PURPOSE" % name)
    missing = [n for n in fd_names if n not in seen]
    if missing:
        raise Failure("no block for: " + ", ".join(missing))

    fd_by_name = dict((f[0], f) for f in funcs)
    entries = []
    for name in sorted(seen):
        sections = seen[name]
        lines = [heading(name), ""]
        for sname, text in sections:
            lines.append("   " + sname)
            for t in text:
                lines.append(("        " + t) if t else "")
            lines.append("")
            if sname == "NAME" and name in fd_by_name:
                _, fd_args, regs = fd_by_name[name]
                lines.append("   SYNOPSIS")
                for t in synopsis(name, fd_args, regs, protos[name]):
                    lines.append(("        " + t) if t else "")
                lines.append("")
        entries.append(lines)

    out = ["TABLE OF CONTENTS", ""]
    out += ["%s/%s" % (LIB, n) for n in sorted(seen)]
    out.append("")
    text = "\n".join(out)
    for lines in entries:
        while lines and not lines[-1]:
            lines.pop()
        text += "\f" + "\n".join(lines) + "\n\n"
    return text.rstrip("\n") + "\n"


def main(argv):
    check = "--check" in argv[1:]
    try:
        doc = build(read(HEADER), read(FD), read(AROS_FD))
    except Failure as e:
        sys.stderr.write("make-autodoc: %s\n" % e)
        return 1
    if check:
        try:
            current = read(OUT)
        except OSError:
            current = None
        if current != doc:
            sys.stderr.write("make-autodoc: %s is not up to date; run "
                             "scripts/make-autodoc.py\n"
                             % os.path.relpath(OUT, ROOT))
            return 1
        print("autodoc: ok, %d entries" % doc.count("\f"))
        return 0
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="ascii") as f:
        f.write(doc)
    print("wrote %s, %d entries" % (os.path.relpath(OUT, ROOT),
                                   doc.count("\f")))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
